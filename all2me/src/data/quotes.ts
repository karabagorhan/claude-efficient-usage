/** Günün sözü: tarihe göre deterministik. */
export function quoteIndexForDay(dayKey: string): number {
  let h = 7;
  for (let i = 0; i < dayKey.length; i++) h = (h * 31 + dayKey.charCodeAt(i)) % 100003;
  return h % QUOTES.length;
}

